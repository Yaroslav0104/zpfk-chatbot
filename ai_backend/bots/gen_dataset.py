UA_ALPHABET = "абвгґдеєжзиіїйклмнопрстуфхцчшщьюя"

def random_ua_chars(length: int) -> str:
    return "".join(random.choice(UA_ALPHABET) for _ in range(length))

def random_mixed_chars(length: int) -> str:
    pool = UA_ALPHABET + string.digits + "!?.,;:-_"
    return "".join(random.choice(pool) for _ in range(length))

def random_repeated_word() -> str:
    words = ["га", "ха", "ей", "ок", "ну", "да", "є", "о", "а", "е", "і", "гей"]
    word = random.choice(words)
    return (word + " ") * random.randint(5, 20)

