def capitalize_first(text):
    text = text.strip()
    if text:
        return text[0].upper() + text[1:]
    return text

def clean_text(text):
    text = " ".join(text.split())
    text = text.replace(" ,", ",").replace(" .", ".").replace(" !", "!").replace(" ?", "?")
    return capitalize_first(text)

