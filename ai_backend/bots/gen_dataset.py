def generate_dataset(
    total_size: int = 5000,
    spam_ratio: float = 0.40,
    output_csv: str = "student_chatbot_dataset.csv",
    output_json: str = "student_chatbot_dataset.json",
) -> list[dict]:

    n_spam = int(total_size * spam_ratio)
    n_ham  = total_size - n_spam
    dataset: list[dict] = []

    print(f"Генерую датасет: {total_size} записів ({n_spam} спам | {n_ham} не спам)…")

    # ── НЕ СПАМ ─────────────────────────────────────────────────────────
    for _ in range(n_ham):
        text = augment_ham(random.choice(HAM_MESSAGES))
        dataset.append({"text": text.strip(), "label": 0})

    # ── СПАМ ─────────────────────────────────────────────────────────────
    fixed_count = int(n_spam * 0.35)
    gen_count   = n_spam - fixed_count

    for _ in range(fixed_count):
        text = augment_spam(random.choice(SPAM_FIXED))
        dataset.append({"text": text.strip(), "label": 1})

    for _ in range(gen_count):
        text = augment_spam(random.choice(SPAM_GENERATORS)())
        dataset.append({"text": text.strip(), "label": 1})

    # ── Перемішати ───────────────────────────────────────────────────────
    random.shuffle(dataset)

    # ── Зберегти CSV ─────────────────────────────────────────────────────
    with open(output_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "label"])
        writer.writeheader()
        writer.writerows(dataset)
    print(f"✅  CSV  → {output_csv}")

    # ── Зберегти JSON ────────────────────────────────────────────────────
    with open(output_json, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)
    print(f"✅  JSON → {output_json}")

    return dataset

