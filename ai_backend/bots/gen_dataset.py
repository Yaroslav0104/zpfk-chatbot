def augment_ham(text: str) -> str:
    """Природні варіації: орфографія, скорочення, живий стиль."""
    if random.random() < 0.3 and text.endswith("."):
        text = text[:-1]
    if random.random() < 0.2:
        text = text[0].lower() + text[1:]
    if random.random() < 0.15:
        text = text.rstrip(".!") + random.choice([", будь ласка", ", прошу допомогти", ", дякую"])
    if random.random() < 0.1:
        text = text.rstrip(".") + "!"
    return text

def augment_spam(text: str) -> str:
    """Підсилює «спамність»: CAPS, зайві знаки, повтори."""
    if random.random() < 0.35:
        text = text.upper()
    if random.random() < 0.3:
        text = text + random.choice(["!!!", "???", "!!??", "...", "!"])
    if random.random() < 0.2:
        text = random.choice(["е е е ", "ну ну "]) + text
    return text

