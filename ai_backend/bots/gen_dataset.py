def generate_samples(templates, count, label):
    samples = set()
    attempts = 0
    while len(samples) < count and attempts < count * 100:
        attempts += 1
        template = random.choice(templates)

        text = template.format(
            intro=random.choice(official_intros),
            pos_word=random.choice(pos_official),
            neg_word=random.choice(neg_official),
            neu_action=random.choice(neu_official_actions),
            topic=random.choice(official_topics)
        )

        samples.add(clean_text(text))

    return [{'text': s, 'label': label} for s in list(samples)[:count]]

