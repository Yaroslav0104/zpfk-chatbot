def print_stats(dataset: list[dict]) -> None:
    total = len(dataset)
    spam  = sum(1 for d in dataset if d["label"] == 1)
    ham   = total - spam
    avg   = sum(len(d["text"]) for d in dataset) / total

    print(f"""
── Статистика ───────────────────────────────────
  Всього записів  : {total}
  Не спам  (0)    : {ham}  ({ham/total*100:.1f}%)
  Спам     (1)    : {spam}  ({spam/total*100:.1f}%)
  Сер. довжина    : {avg:.0f} символів
─────────────────────────────────────────────────""")

    print("\n  [0] Приклади НЕ СПАМ:")
    for d in random.sample([x for x in dataset if x["label"] == 0], 5):
        print(f"      {d['text'][:95]}")

    print("\n  [1] Приклади СПАМ:")
    for d in random.sample([x for x in dataset if x["label"] == 1], 5):
        print(f"      {d['text'][:95]}")
    print()

